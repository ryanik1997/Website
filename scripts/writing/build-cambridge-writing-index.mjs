#!/usr/bin/env node
import fs from 'node:fs/promises'
import path from 'node:path'
import { CAMBRIDGE_WRITING_LEVELS } from './cambridge-writing-level-config.mjs'
import { ROOT, listGeneratedFiles, readJson } from './cambridge-writing-runtime.mjs'

const OUTPUT = path.join(ROOT, 'packages/catalog/src/cambridge/writing/generatedData.ts')

async function main() {
  const files = await listGeneratedFiles('all')
  const grouped = Object.fromEntries(CAMBRIDGE_WRITING_LEVELS.map(level => [level, []]))
  for (const file of files) {
    const value = await readJson(file)
    if (value.level === 'a2') throw new Error(`AI-generated A2 data is forbidden: ${file}`)
    grouped[value.level].push({ file, value })
  }
  for (const level of CAMBRIDGE_WRITING_LEVELS) {
    grouped[level].sort((a, b) => a.value.testNumber - b.value.testNumber)
    const numbers = new Set()
    for (const item of grouped[level]) {
      if (numbers.has(item.value.testNumber)) throw new Error(`${level}: duplicate test number ${item.value.testNumber}`)
      numbers.add(item.value.testNumber)
    }
  }
  const imports = []
  const variables = Object.fromEntries(CAMBRIDGE_WRITING_LEVELS.map(level => [level, []]))
  let index = 0
  for (const level of CAMBRIDGE_WRITING_LEVELS) {
    for (const item of grouped[level]) {
      const name = `generatedTest${index}`
      const relative = path.relative(path.dirname(OUTPUT), item.file).replaceAll('\\', '/')
      imports.push(`import ${name} from '${relative.startsWith('.') ? relative : `./${relative}`}'`)
      variables[level].push(name)
      index += 1
    }
  }
  const lines = [
    '// Generated by scripts/writing/build-cambridge-writing-index.mjs. Do not edit manually.',
    ...imports,
    "import type { CambridgeWritingTest } from './schema.ts'",
    '',
    'export const CAMBRIDGE_WRITING_GENERATED_TESTS = {',
    ...CAMBRIDGE_WRITING_LEVELS.map(level => `  ${level}: [${variables[level].join(', ')}] as CambridgeWritingTest[],`),
    '} as const',
    '',
  ]
  await fs.writeFile(OUTPUT, lines.join('\n'))
  console.log(`Generated index with ${files.length} tests: ${path.relative(ROOT, OUTPUT)}`)
}

main().catch(error => { console.error(error instanceof Error ? error.message : error); process.exitCode = 1 })
